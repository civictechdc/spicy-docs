            capture = probe.get(url, media_types=media_types, max_bytes=SAMPLE_MAX_BYTES)
            facts = {"url": url, **_capture_facts(capture)}
            if media_types is JSON_TYPES:
                facts["shape"] = _json_shape(json.loads(capture.body))
