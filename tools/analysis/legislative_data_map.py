def _ordinal(n: int) -> str:
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def _cell(text: object) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _congress_cells(facts: Mapping[str, Any]) -> tuple[str, str]:
    if "totalError" in facts and "earliest" not in facts:
        return "error", facts["totalError"].get("message", "")[:60]
    total = facts.get("total")
    count = f"{total:,}" if isinstance(total, int) else ""
    earliest = facts.get("earliest")
    path = facts.get("descentPath", "")
    if earliest is None:
        coverage = "" if not path else f"none found ({facts.get('descentStop')})"
    elif "daily" in path:
        coverage = f"vol. {earliest}+"
    elif "bound" in path:
        coverage = f"{earliest}+"
    else:
        coverage = f"{_ordinal(earliest)} Congress+"
    if facts.get("descentStop") in ("cap", "error") and earliest is not None:
        coverage = f"≥ {coverage[:-1]} ({facts['descentStop']})"
    if facts.get("floorGap"):
        keys = ", ".join(str(k) for k in facts["floorGap"])
        if facts.get("descentStop") == "cap":
            coverage += f" (continues below the cap: {keys} populated)"
        else:
            coverage += f" (populated again at {keys}: a gap wider than the walk's stop)"
    latest = facts.get("latestUpdate")
    if latest:
        stamp = str(latest)[:10]
        phrase = f"latest {stamp}" if facts.get("latestSortHonored") else f"updated ≥ {stamp} (sort ignored)"
        coverage = f"{coverage}; {phrase}" if coverage else phrase
    return coverage, count


def _govinfo_cells(measures: Mapping[str, Any], code: str) -> tuple[str, str]:
    inventory = measures.get("collections", {}).get(code, {})
    coverage = measures.get("coverage", {}).get(code, {})
    bulk = measures.get("bulkdata", {}).get(code)
    year = coverage.get("earliestYear")
    cov = [f"API {year}+" if year else ("API error" if coverage.get("error") else "")]
    total, count = coverage.get("total"), inventory.get("packageCount")
    if isinstance(total, int) and isinstance(count, int) and total != count:
        # The year search counts packages with an issue date; the inventory counts all. The gap is packages undated.
        cov[0] += f" ({count - total:,} inventory packages undated)"
    if bulk:
        rng = bulk.get("numericRange")
        cov.append(f"bulk {rng[0]}–{rng[1]}" if rng else "bulk, flat")
    parts = []
    if isinstance(inventory.get("packageCount"), int):
        parts.append(f"{inventory['packageCount']:,} pkgs")
    if bulk and bulk.get("topLevelFiles"):
        parts.append(f"bulk {bulk['topLevelFiles']:,} files, {bulk['topLevelBytes'] / 1e6:,.0f} MB")
    current = (bulk or {}).get("currentCongress") or {}
    if current.get("types") and not current.get("zipBytes") and not current.get("fileBytes"):
        parts.append(
            f"{_ordinal(current['congress'])} bulk nested one level deeper ({', '.join(current['types'])}); unsized"
        )
    elif current.get("zipBytes") or current.get("fileBytes"):
        modified = next((t.get("zipModified") for t in current.get("types", {}).values() if t.get("zipModified")), None)
        parts.append(
            f"{_ordinal(current['congress'])} zips {current['zipBytes'] / 1e6:,.0f} MB, {current['files']:,} files"
            + (f", zip modified {modified}" if modified else "")
        )
    return "; ".join(c for c in cov if c), "; ".join(parts)


def _sample_cells(facts: Mapping[str, Any]) -> tuple[str, str]:
    if "error" in facts:
        reason = facts.get("message", facts["error"]).split(";")[0][:70]
        return "", f"sample refused: HTTP {facts['statusCode']}" if facts.get(
            "statusCode"
        ) else f"sample refused: {reason}"
    shape = facts.get("shape", {})
    root = shape.get("root")
    if root:
        identity = _identity_order(shape.get("identityNames") or [])
        dated = shape.get("datedNames") or []
        if identity:
            stated = f"names {', '.join(identity[:4])}"
        elif dated:
            stated = f"dated only ({', '.join(dated[:2])})"
        else:
            stated = "no identity element within two levels"
        detail = f"root `{root}`, {shape.get('childCount', 0)} children; {stated}"
    elif shape.get("idKinds"):
        kinds = shape["idKinds"]
        named = ", ".join(
            f"{k} {v:,}"
            for k, v in kinds.items()
            if k in ("bioguide", "lis", "fec", "icpsr", "govtrack", "opensecrets")
        )
        detail = f"{shape.get('count', 0):,} records; ids {named}"
    elif isinstance(shape.get("count"), int):
        detail = f"declares {shape['count']:,} records"
    elif shape.get("html"):
        detail = "HTML page"
    else:
        detail = f"keys {', '.join(shape.get('keys', [])[:4])}"
    return "", f"sample {facts.get('byteSize', 0):,} B, {detail}"


def _cells(row: Row, measures: Mapping[str, Any]) -> tuple[str, str]:
    if row.measure is None:
        return "", ""
    kind, key = row.measure
    if kind == "congress":
        return _congress_cells(measures.get("congress", {}).get(key, {}))
    if kind == "govinfo":
        return _govinfo_cells(measures.get("govinfo", {}), key)
    if kind == "sample":
        return _sample_cells(measures.get("samples", {}).get(key, {}))
    if kind == "cdtf":
        entry = measures.get("catalog", {}).get("byId", {}).get(key, {})
        return "", f"CDTF #{key}, {entry.get('accrualPeriodicity', '')}"
    raise ValueError(f"unknown measure kind {kind!r}")


