#: The editions the corpus is drawn from: several titles, several years, one
#: volume each. Chosen for breadth of subject matter and typography (a
#: definitions-heavy title, a tabular one, a long regulatory one) rather than
#: for how well any of them reconstructs.
EDITIONS: tuple[tuple[int, int, int], ...] = (
    (2025, 30, 3),
    (2024, 12, 1),
    (2023, 7, 1),
    (2022, 40, 1),
)
#: The split each edition falls in. Whole editions, so no volume's typography
#: reaches two splits (§3.2: "blind splits grouped by edition").
SPLITS: dict[int, str] = {2025: "development", 2024: "tuning", 2023: "blind", 2022: "blind"}
CONTENT = "https://www.govinfo.gov"
#: A section granule's PDF; the sibling of the XML locator `sources/cfr` derives.
PDF_TEMPLATE = CONTENT + "/content/pkg/{package}/pdf/{granule}.pdf"
CONTENT_CLASS = "CONTENT"
MAX_PDF_BYTES = 24 * 1024 * 1024
MAX_XML_BYTES = 8 * 1024 * 1024
#: The proposal's target corpus; this run is a first, bounded slice of it.
TARGET_SECTIONS = 500


class BenchmarkError(ValueError):
    """The corpus cannot be built or scored as asked; a ValueError, as every acquirer here refuses with one."""


# --- fetching -------------------------------------------------------------------------


class KeylessBody(SourceAcquirer):
    """One bounded keyless GET per call, with the publisher's error page refused as absence.

    GovInfo answers a rendition it does not have with a redirect to `/error`,
    which returns HTTP 200; `sources/govinfo/error_page.py` holds both
    witnesses and this reuses them rather than restating the rule.
    """

    def __init__(self, *, timeout_seconds: float, min_request_interval_seconds: float) -> None:
        super().__init__(
            max_requests=2,
            timeout_seconds=timeout_seconds,
            min_request_interval_seconds=min_request_interval_seconds,
            user_agent="spicy-docs-reconstruction-benchmark/1.0",
            label="body",
            error_type=BenchmarkError,
            context_key="reconstruction_benchmark",
            keyless=True,
        )
        self.requests = 0
        self.log: list[dict[str, Any]] = []

    def get(self, url: str, *, media_types: tuple[str, ...], max_bytes: int) -> CapturedBodyResponse:
        self.requests += 1
        _, capture = self.capture_validated(
            url,
            media_types=media_types,
            parse=lambda capture, _limit: capture,
            max_bytes=max_bytes,
            unavailable=lambda capture: BenchmarkError(f"HTTP {capture.status_code} for {url}"),
            context={"operation": "body", "url": url},
        )
        self.log.append(
            {
                "url": url,
                "resolvedUrl": capture.resolved_url,
                "statusCode": capture.status_code,
                "contentType": capture.content_type,
                "byteSize": capture.byte_size,
                "sha256": capture.sha256,
                "observedAt": capture.observed_at,
            }
        )
        if is_error_page_url(capture.resolved_url) or has_error_page_marker(capture.body):
            raise BenchmarkError(f"{url} answered the publisher's error page, not the object")
        return capture


@dataclass(frozen=True, slots=True)
class Granule:
    """One paired item: the publisher's granule id and the two renditions it is served in."""

    year: int
    title: int
    volume: int
    granule_id: str
    section: str

    @property
    def package(self) -> str:
        return f"CFR-{self.year}-title{self.title}-vol{self.volume}"

    @property
    def split(self) -> str:
        return SPLITS.get(self.year, "blind")

    @property
    def pdf_url(self) -> str:
        return PDF_TEMPLATE.format(package=self.package, granule=self.granule_id)

    @property
    def xml_url(self) -> str:
        return annual_cfr_xml_locator(AnnualCfrSelection(self.year, self.title, self.volume, self.section))


def _section_number(granule_id: str, package: str) -> str | None:
    """``CFR-2025-title30-vol3-sec716-2`` names section ``716.2``; anything else is not a section granule."""
    stem = granule_id.removeprefix(package + "-")
    if not stem.startswith("sec") or stem == granule_id:
        return None
    return stem.removeprefix("sec").replace("-", ".", 1)


@dataclass(frozen=True, slots=True)
class Listing:
    """One edition's sample and what the listing that produced it could see."""

    granules: tuple[Granule, ...]
    listed: int
    sections: int
    declared: int | None
    complete: bool
    stride: int


def choose_granules(reader: GovInfoDiscoveryReader, edition: tuple[int, int, int], wanted: int) -> Listing:
    """Take ``wanted`` section granules at an even stride through one volume's listing, in one request.

    One page of up to 1,000 granules is read. A volume with more than that is
    *not* walked further -- the request budget buys paired bodies, not a
    complete inventory -- so the sample is spread across what that page listed
    and ``complete`` records whether the page was the whole volume. The
    publisher's declared count is kept beside it, so a reader can see how much
    of the volume the stride ran over.
    """
    year, title, volume = edition
    package = f"CFR-{year}-title{title}-vol{volume}"
    rows: list[Mapping[str, Any]] = []
    declared: int | None = None
    complete = True
    try:
        for page in reader.granules(package_granules_url(package, page_size=1000), max_pages=1):
            rows.extend(page.records)
            declared = page.declared_count if declared is None else declared
    except PagedJsonSourceError:
        # The reader refuses a walk that ends at its page bound rather than at
        # the publisher's last page; here the bound is the point, so the
        # refusal is recorded as an incomplete listing, not as a failure.
        complete = False
    sections: list[Granule] = []
    for row in rows:
        granule_id = row.get("granuleId")
        if not isinstance(granule_id, str) or row.get("granuleClass") != CONTENT_CLASS:
            continue
        number = _section_number(granule_id, package)
        if number is None:
            continue
        candidate = Granule(year, title, volume, granule_id, number)
        try:
            # The locator refuses a section spelling `sources/cfr` does not
            # support; such a granule is skipped rather than guessed at.
            _ = candidate.xml_url
        except CfrSourceError:
            continue
        sections.append(candidate)
    if not sections:
        raise BenchmarkError(f"{package} listed no section granule in its first page")
    stride = max(len(sections) // wanted, 1)
    return Listing(tuple(sections[::stride][:wanted]), len(rows), len(sections), declared, complete, stride)


# --- the reference side ------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Reference:
    """The published granule, read only *after* the reconstruction is made."""

    text: str
    markers: tuple[str, ...]
    elements: tuple[str, ...]
    section: str | None


def read_reference(xml: bytes) -> Reference:
    """Read the published section: its text, its paragraph markers and its element names.

    The reader is this repository's bounded XML event reader, and the external
    DOCTYPE a GPO file may declare is tolerated and never resolved, exactly as
    ``extraction/body_text.py`` tolerates the BILLS one.
    """
    read = read_xml_events(xml, allow_external_doctype=True, max_bytes=MAX_XML_BYTES)
    stack: list[str] = []
    texts: dict[int, list[str]] = {}
    order: list[tuple[int, str]] = []
    section_number: str | None = None
    index = -1
    for event in read.events:
        if event.kind in ("start", "empty"):
            stack.append(event.name or "")
            if len(stack) >= 2 and stack[-2] == "SECTION" and event.kind == "start":
                index += 1
                order.append((index, event.name or ""))
                texts[index] = []
            if event.kind == "empty":
                stack.pop()
            continue
        if event.kind == "end":
            if stack:
                stack.pop()
            continue
        if event.kind != "text" or not event.text or not event.text.strip():
            continue
        if "SECTION" not in stack:
            continue
        if order:
            texts[order[-1][0]].append(event.text.strip())
    chunks = [(name, " ".join(texts[position])) for position, name in order]
    for name, text in chunks:
        if name == "SECTNO" and section_number is None:
            section_number = text.strip().removeprefix("§").strip()
    markers = tuple(marker for name, text in chunks if name == "P" and (marker := paragraph_marker(text)))
    return Reference(
        text=" ".join(text for _name, text in chunks if text),
        markers=markers,
        elements=tuple(name for name, _text in chunks),
        section=section_number,
    )


# --- the candidate side -------------------------------------------------------------------


def reconstruct(pdf: bytes) -> tuple[EvidenceDocument, ReconstructedDocument]:
    """Extract, model and parse one section PDF. It never sees the XML."""
    evidence = evidence_from_pages(DocumentExtractor(NativeText()).extract(pdf, media_type="application/pdf"))
    return evidence, parse_cfr(evidence)


def score(
    granule: Granule,
    document: ReconstructedDocument,
    serialized: Serialized,
    reference: Reference,
    *,
    schema: bool,
) -> dict[str, Any]:
    """Every number this benchmark reports for one document, from the findings and the reference."""
    findings = validate.check(
        document,
        serialized,
        section=granule.section,
        reference_text=reference.text,
        reference_markers=reference.markers,
        schema=schema,
    )
    by_name = {finding.check: finding for finding in findings}
    comparison = validate.compare_text(reference.text, validate.serialized_text(serialized))
    f1, shared, reference_pairs, candidate_pairs = validate.hierarchy_f1(
        validate.marker_pairs(reference.markers),
        validate.document_marker_pairs(document, section=granule.section),
    )
    coverage = by_name["coverage"].measures
    return {
        "precision": comparison.precision,
        "recall": comparison.recall,
        "referenceTokens": comparison.reference_tokens,
        "candidateTokens": comparison.candidate_tokens,
        "criticalDiscrepancies": len(comparison.critical),
        "criticalSample": list(dict.fromkeys(comparison.critical))[:8],
        "hierarchyF1": f1,
        "hierarchyShared": shared,
        "referencePairs": reference_pairs,
        "candidatePairs": candidate_pairs,
        "blocks": coverage["blocks"],
        "outOfScopeBlocks": coverage["outOfScopeBlocks"],
        "unresolvedRegions": coverage["unresolvedRegions"],
        "nodesNeedingReview": coverage["nodesNeedingReview"],
        "sectionsInRendition": by_name["structural_fidelity"].measures["sections"],
        "findings": [finding.to_json() for finding in findings],
        "accepted": by_name["acceptance"].passed,
    }


# --- the run ---------------------------------------------------------------------------------


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def measure(
    granules: Sequence[Granule],
    bodies: KeylessBody,
    scratch: Path,
    *,
    schema: bool,
    max_requests: int,
    api_key: str,
) -> Iterator[dict[str, Any]]:
    """Fetch, reconstruct and score one granule at a time, yielding a row for each."""
    for granule in granules:
        if bodies.requests + 2 > max_requests:
            raise BenchmarkError(f"request budget {max_requests} reached before {granule.granule_id}")
        row: dict[str, Any] = {
            "granuleId": granule.granule_id,
            "package": granule.package,
            "year": granule.year,
            "title": granule.title,
            "volume": granule.volume,
            "section": granule.section,
            "split": granule.split,
            "pdfUrl": granule.pdf_url,
            "xmlUrl": granule.xml_url,
        }
        started = time.perf_counter()
        try:
            pdf = bodies.get(granule.pdf_url, media_types=("application/pdf",), max_bytes=MAX_PDF_BYTES)
            check_pdf_bytes(pdf.body, error_type=BenchmarkError, label=f"{granule.granule_id} PDF")
            xml = bodies.get(granule.xml_url, media_types=("application/xml", "text/xml"), max_bytes=MAX_XML_BYTES)
        except (BenchmarkError, ValueError) as error:
            row |= {"error": type(error).__name__, "message": scrub_credential(str(error), api_key)[:300]}
            yield row
            continue
        (scratch / f"{granule.granule_id}.pdf").write_bytes(pdf.body)
        (scratch / f"{granule.granule_id}.xml").write_bytes(xml.body)
        row |= {
            "pdfBytes": pdf.byte_size,
            "pdfSha256": _digest(pdf.body),
            "xmlBytes": xml.byte_size,
            "xmlSha256": _digest(xml.body),
        }
        fetched = time.perf_counter()
        try:
            evidence, document = reconstruct(pdf.body)
            serialized = serialize_cfr(document, section=granule.section)
            reference = read_reference(xml.body)
            row |= score(granule, document, serialized, reference, schema=schema)
            row["pages"] = evidence.page_count
        except (ValueError, KeyError) as error:
            row |= {"error": type(error).__name__, "message": str(error)[:300]}
            yield row
            continue
        done = time.perf_counter()
        row |= {"fetchSeconds": round(fetched - started, 3), "reconstructSeconds": round(done - fetched, 3)}
        yield row


def _mean(values: Sequence[float | None]) -> float | None:
    """The mean of the values that exist; ``None`` when none do, never a zero standing in for absence."""
    known = [value for value in values if value is not None]
    return round(statistics.fmean(known), 6) if known else None


def summarize(rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Aggregate scored rows overall and per split; a failed row counts against the total, never silently."""
    scored = [row for row in rows if "precision" in row]
    failed = [row for row in rows if "error" in row]
    summary: dict[str, Any] = {
        "documents": len(rows),
        "scored": len(scored),
        "failed": len(failed),
        "failures": [{"granuleId": row["granuleId"], "error": row["error"]} for row in failed][:20],
    }
    for name, subset in [("all", scored)] + [
        (split, [row for row in scored if row["split"] == split]) for split in sorted({row["split"] for row in scored})
    ]:
        if not subset:
            continue
        laddered = [row for row in subset if row["referencePairs"]]
        summary[name] = {
            "documents": len(subset),
            "precision": _mean([row["precision"] for row in subset]),
            "recall": _mean([row["recall"] for row in subset]),
            "hierarchyF1": _mean([row["hierarchyF1"] for row in subset]),
            # Sections whose published text has no designated paragraph at all
            # score a vacuous 1.0; this is the mean over the ones that do have
            # a ladder to get wrong, which is the number worth reading.
            "hierarchyF1WithLadder": _mean([row["hierarchyF1"] for row in laddered]),
            "documentsWithLadder": len(laddered),
            "documentsWithCriticalDiscrepancy": sum(1 for row in subset if row["criticalDiscrepancies"]),
            "criticalDiscrepancies": sum(row["criticalDiscrepancies"] for row in subset),
            "unresolvedRegions": sum(row["unresolvedRegions"] for row in subset),
            "outOfScopeBlocks": sum(row["outOfScopeBlocks"] for row in subset),
            "blocks": sum(row["blocks"] for row in subset),
            "accepted": sum(1 for row in subset if row["accepted"]),
            "schemaValid": sum(1 for row in subset if _finding(row, "schema_validity")),
            "contentFidelity": sum(1 for row in subset if _finding(row, "content_fidelity")),
            "structuralFidelity": sum(1 for row in subset if _finding(row, "structural_fidelity")),
            "coverageComplete": sum(1 for row in subset if _finding(row, "coverage")),
            "reconstructSeconds": _mean([row.get("reconstructSeconds") for row in subset]),
            "fetchSeconds": _mean([row.get("fetchSeconds") for row in subset]),
        }
    return summary


def _finding(row: Mapping[str, Any], check: str) -> bool:
    return any(finding["check"] == check and finding["passed"] for finding in row.get("findings", ()))


def rescore(
    previous: Mapping[str, Any], scratch: Path, *, schema: bool
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Re-run reconstruction and scoring over bodies an earlier run already fetched.

    Every file is checked against the digest the earlier run recorded before it
    is read, so a re-score cannot quietly measure different bytes than the
    numbers it replaces; a body whose digest moved, or that is missing, is
    reported rather than skipped. This exists because a change to a parsing
    rule must be measurable without spending the publisher's bandwidth again.
    """
    rows: list[dict[str, Any]] = []
    manifest: list[dict[str, Any]] = []
    for old in previous.get("documents", []):
        row = {key: old[key] for key in ("granuleId", "package", "year", "title", "volume", "section", "split")}
        row |= {"pdfUrl": old["pdfUrl"], "xmlUrl": old["xmlUrl"]}
        granule = Granule(old["year"], old["title"], old["volume"], old["granuleId"], old["section"])
        pdf_path = scratch / f"{granule.granule_id}.pdf"
        xml_path = scratch / f"{granule.granule_id}.xml"
        if not pdf_path.exists() or not xml_path.exists():
            row |= {"error": "MissingBody", "message": f"{scratch} holds no body for {granule.granule_id}"}
            rows.append(row)
            continue
        pdf, xml = pdf_path.read_bytes(), xml_path.read_bytes()
        digests = {"pdfSha256": _digest(pdf), "xmlSha256": _digest(xml)}
        for name in ("pdfSha256", "xmlSha256"):
            if name in old and old[name] != digests[name]:
                row |= {"error": "DigestMoved", "message": f"{name} is {digests[name]}, not the recorded {old[name]}"}
                break
        else:
            row |= {"pdfBytes": len(pdf), "xmlBytes": len(xml)} | digests
            manifest.append(
                {
                    "granuleId": granule.granule_id,
                    "split": granule.split,
                    "pdfUrl": granule.pdf_url,
                    "pdfBytes": len(pdf),
                    "pdfSha256": digests["pdfSha256"],
                    "xmlUrl": granule.xml_url,
                    "xmlBytes": len(xml),
                    "xmlSha256": digests["xmlSha256"],
                }
            )
            started = time.perf_counter()
            try:
                evidence, document = reconstruct(pdf)
                serialized = serialize_cfr(document, section=granule.section)
                row |= score(granule, document, serialized, read_reference(xml), schema=schema)
                row["pages"] = evidence.page_count
                row["reconstructSeconds"] = round(time.perf_counter() - started, 3)
                row["fetchSeconds"] = old.get("fetchSeconds")
            except (ValueError, KeyError) as error:
                row |= {"error": type(error).__name__, "message": str(error)[:300]}
        rows.append(row)
    return rows, manifest


def write_receipts(directory: Path, measures: Mapping[str, Any], *, command: Sequence[str], log: Sequence[str]) -> None:
    """Retain the command, the run log, the request log and the corpus manifest outside the repository.

    AGENTS.md: a measurement needs its input pins, its command and its retained
    receipt, and campaign receipts live outside this repository. The committed
    JSON sidecar is the pin; this folder is the receipt behind it.
    """
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "command.txt").write_text(" ".join(command) + "\n")
    (directory / "run.log").write_text("\n".join(log) + "\n")
    (directory / "requests.jsonl").write_text(
        "".join(json.dumps(entry, sort_keys=True) + "\n" for entry in measures.get("requestLog", []))
    )
    (directory / "corpus-manifest.json").write_text(
        json.dumps(
            {
                "generatedAt": measures.get("generatedAt"),
                "profile": measures.get("profile"),
                "guideSha256": measures.get("guideSha256"),
                "schemaSha256": measures.get("schemaSha256"),
                "editions": measures.get("editions"),
                "listings": measures.get("listings"),
                "bodies": measures.get("manifest", []),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    (directory / "summary.json").write_text(json.dumps(measures.get("summary", {}), indent=2, sort_keys=True) + "\n")
    scored_from = measures.get("scoredFrom")
    requests = measures.get("requests", {})
    origin = (
        f"The bodies were fetched by an earlier run of this tool at revision "
        f"`{scored_from.get('fetchRevision')}` on {str(scored_from.get('fetchedAt'))[:19]} "
        f"({(scored_from.get('requests') or {}).get('total', '?')} requests); this run re-read them from "
        f"`{scored_from.get('bodies')}` and made **no request**. Each body's digest was checked against the one "
        "that run recorded before it was read, so these numbers are over the same bytes.\n\n"
        "`requests.jsonl` is therefore empty; `fetch-command.txt` holds the command that did make the requests, "
        "and `corpus-manifest.json` is the fetch's retained evidence: every body's URL, byte size and SHA-256.\n"
        if scored_from
        else f"This run made {requests.get('total', '?')} requests; `requests.jsonl` lists each one with its "
        "resolved URL, status, byte size and digest.\n"
    )
    (directory / "README.md").write_text(
        f"""# Reconstruction benchmark receipt

The retained receipt behind
`docs/research/reconstruction-benchmark-2026-09-19.json` in spicy-docs, kept
outside that repository per its AGENTS.md. The committed sidecar is the pin;
this folder is the evidence behind it.

| File | What it is |
| --- | --- |
| `command.txt` | The exact command that produced the numbers |
| `fetch-command.txt` | The command that fetched the corpus, when that was a separate run |
| `run.log` | Its per-document progress output |
| `requests.jsonl` | One line per HTTP request: URL, resolved URL, status, content type, bytes, SHA-256, time |
| `corpus-manifest.json` | Every paired body: URL, byte size, SHA-256, split, plus the profile and listing pins |
| `summary.json` | The aggregate the report's generated block was rendered from |

Input pins: profile `{measures.get("profile")}`, GPO CFR XML user guide sha256
`{measures.get("guideSha256")}`, pinned schema `CFRMergedXML.xsd` sha256
`{measures.get("schemaSha256")}`.

{origin}
The fetched bodies themselves are public-domain U.S. government documents and
are not retained here; the manifest's digests re-derive them from the URLs.
"""
    )


# --- the report -------------------------------------------------------------------------------


def _percent(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.2f}%"


def render_block(measures: Mapping[str, Any]) -> str:
    """The markdown between the markers, rendered from the sidecar alone; a fixture test runs this."""
    summary = measures.get("summary", {})
    rows = measures.get("documents", [])
    gates = measures.get("gates", {})
    lines = [MARK_START, ""]
    lines.append(
        f"Measured {summary.get('scored', 0)} of {summary.get('documents', 0)} paired sections on "
        f"{measures.get('generatedAt', 'an unrecorded date')[:10]} at revision "
        f"`{measures.get('revision', 'unknown')}`, {measures.get('requests', {}).get('total', 0)} requests. "
        f"The proposal's target corpus is {TARGET_SECTIONS} sections; this is the first bounded slice."
    )
    lines.append("")
    lines.append("### Against the §3.3 gates")
    lines.append("")
    lines.append("| Gate | Target | All | Development | Tuning | Blind |")
    lines.append("|---|---|---|---|---|---|")
    splits = ("all", "development", "tuning", "blind")

    def cell(split: str, render) -> str:
        block = summary.get(split)
        return "-" if not block else render(block)

    lines.append(
        "| Text precision | ≥ 99.9% | "
        + " | ".join(cell(split, lambda b: _percent(b["precision"])) for split in splits)
        + " |"
    )
    lines.append(
        "| Text recall | ≥ 99.9% | "
        + " | ".join(cell(split, lambda b: _percent(b["recall"])) for split in splits)
        + " |"
    )
    lines.append(
        "| Hierarchy F1, all sections | ≥ 0.98 | "
        + " | ".join(
            cell(split, lambda b: f"{b['hierarchyF1']:.4f}" if b["hierarchyF1"] is not None else "n/a")
            for split in splits
        )
        + " |"
    )
    lines.append(
        "| Hierarchy F1, sections with a paragraph ladder | ≥ 0.98 | "
        + " | ".join(
            cell(
                split,
                lambda b: (
                    "n/a"
                    if b["hierarchyF1WithLadder"] is None
                    else f"{b['hierarchyF1WithLadder']:.4f} ({b['documentsWithLadder']} of {b['documents']})"
                ),
            )
            for split in splits
        )
        + " |"
    )
    lines.append(
        "| Documents with a critical discrepancy | 0 | "
        + " | ".join(
            cell(split, lambda b: f"{b['documentsWithCriticalDiscrepancy']} of {b['documents']}") for split in splits
        )
        + " |"
    )
    lines.append(
        "| Schema valid | all | "
        + " | ".join(cell(split, lambda b: f"{b['schemaValid']} of {b['documents']}") for split in splits)
        + " |"
    )
    lines.append(
        "| Every region accounted for | all | "
        + " | ".join(cell(split, lambda b: f"{b['coverageComplete']} of {b['documents']}") for split in splits)
        + " |"
    )
    lines.append(
        "| Accepted without review | ≥ 70% | "
        + " | ".join(
            cell(split, lambda b: f"{b['accepted'] / b['documents'] * 100:.0f}% ({b['accepted']} of {b['documents']})")
            for split in splits
        )
        + " |"
    )
    lines.append("")
    lines.append(f"Gate thresholds as run: `{json.dumps(gates, sort_keys=True)}`.")
    lines.append("")
    lines.append("### Per edition")
    lines.append("")
    lines.append(
        "| Edition | Split | Sections | Precision | Recall | Hierarchy F1 | With a ladder | Out-of-scope blocks | Accepted |"
    )
    lines.append("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for year, title, volume in EDITIONS:
        subset = [row for row in rows if row.get("year") == year and row.get("title") == title and "precision" in row]
        package = f"CFR-{year}-title{title}-vol{volume}"
        if not subset:
            lines.append(f"| `{package}` | {SPLITS.get(year, 'blind')} | 0 | - | - | - | - | - | - |")
            continue
        blocks = sum(row["blocks"] for row in subset)
        out_of_scope = sum(row["outOfScopeBlocks"] for row in subset)
        lines.append(
            f"| `{package}` | {SPLITS.get(year, 'blind')} | {len(subset)} "
            f"| {_percent(_mean([row['precision'] for row in subset]))} "
            f"| {_percent(_mean([row['recall'] for row in subset]))} "
            f"| {_mean([row['hierarchyF1'] for row in subset]):.4f} "
            f"| {sum(1 for row in subset if row['referencePairs'])} "
            f"| {out_of_scope} of {blocks} "
            f"| {sum(1 for row in subset if row['accepted'])} |"
        )
    lines.append("")
    lines.append("### Where it fails")
    lines.append("")
    reasons: dict[str, int] = {}
    for row in rows:
        if "error" in row:
            reasons[f"fetch or parse error: {row['error']}"] = (
                reasons.get(f"fetch or parse error: {row['error']}", 0) + 1
            )
            continue
        for finding in row.get("findings", ()):
            if finding["check"] in ("acceptance", "schema_validity") or finding["passed"]:
                continue
            key = f"{finding['check']}: {finding['detail'].split(':')[0][:80]}"
            reasons[key] = reasons.get(key, 0) + 1
        if row.get("criticalDiscrepancies"):
            reasons["a number, date, negation or marker differs from the published XML"] = (
                reasons.get("a number, date, negation or marker differs from the published XML", 0) + 1
            )
    if reasons:
        lines.append("| Reason | Documents |")
        lines.append("|---|---:|")
        for reason, count in sorted(reasons.items(), key=lambda item: (-item[1], item[0])):
            lines.append(f"| {reason} | {count} |")
    else:
        lines.append("No document failed a check in this run.")
    lines.append("")
    worst = sorted((row for row in rows if "recall" in row), key=lambda row: row["recall"])[:5]
    if worst:
        lines.append("Lowest recall in this run:")
        lines.append("")
        lines.append("| Granule | Recall | Precision | Hierarchy F1 | Unresolved | Out of scope | Sections in PDF |")
        lines.append("|---|---:|---:|---:|---:|---:|---:|")
        for row in worst:
            lines.append(
                f"| `{row['granuleId']}` | {_percent(row['recall'])} | {_percent(row['precision'])} "
                f"| {row['hierarchyF1']:.4f} | {row['unresolvedRegions']} "
                f"| {row['outOfScopeBlocks']} of {row['blocks']} | {len(row['sectionsInRendition'])} |"
            )
        lines.append("")
    lines.append(
        "A section PDF is a page range of the printed volume and carries neighbouring material; those blocks are "
        "counted as out-of-scope evidence, not as loss (the 'Sections in PDF' column above is how many section "
        "headings each rendition actually contained)."
    )
    lines.append("")
    receipts = measures.get("receipts")
    if receipts:
        lines.append(
            f"Receipt: `{receipts}` (the command, the run log, the request log and the corpus manifest with every "
            "body's URL, byte size and SHA-256). The JSON sidecar beside this file is the committed pin; the bodies "
            "themselves stay outside the repository."
        )
        lines.append("")
    lines.append(MARK_END)
    return "\n".join(lines)


def rewrite_report(path: Path, block: str) -> None:
    text = path.read_text()
    start, end = text.find(MARK_START), text.find(MARK_END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(f"{path} lacks the generated-block markers")
    path.write_text(text[:start] + block + text[end + len(MARK_END) :])


def _revision(root: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True, check=False
    )
    return result.stdout.strip() or "unknown"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True, help="the measurements JSON; read with --offline")
    parser.add_argument("--report", type=Path, required=True, help="the markdown whose generated block is rewritten")
    parser.add_argument("--env-file", type=Path, default=Path(".env"), help="file holding the api.data.gov key")
    parser.add_argument("--env-var", default="API_GOV")
    parser.add_argument(
        "--sections", type=int, default=40, help=f"paired sections to build; the target is {TARGET_SECTIONS}"
    )
    parser.add_argument("--max-requests", type=int, default=120)
    parser.add_argument("--scratch", type=Path, help="where the fetched bodies land; defaults to a temp directory")
    parser.add_argument("--offline", action="store_true", help="re-render the report from --output without the network")
    parser.add_argument(
        "--rescore",
        action="store_true",
        help="re-reconstruct and re-score the bodies an earlier run left in --scratch; no request is made",
    )
    parser.add_argument("--receipts", type=Path, help="retain the command, logs and corpus manifest in this directory")
    parser.add_argument("--min-interval-seconds", type=float, default=0.3)
    parser.add_argument("--timeout", type=float, default=60.0)
    parser.add_argument("--no-schema", action="store_true", help="skip the check that needs the reconstruct extra")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[2]

    command = [
        "uv", "run", "--frozen", "python", "-m", "tools.analysis.reconstruction_benchmark",
        *(argv if argv is not None else sys.argv[1:]),
    ]  # fmt: skip
    log: list[str] = []

    def note(line: str) -> None:
        log.append(line)
        print(line, file=sys.stderr)

    if args.offline:
        measures = json.loads(args.output.read_text())
        rewrite_report(args.report, render_block(measures))
        print(json.dumps({"output": str(args.output), "report": str(args.report), "offline": True}))
        return 0

    if args.rescore:
        if args.scratch is None:
            parser.error("--rescore needs --scratch, the directory the earlier run wrote its bodies to")
        previous = json.loads(args.output.read_text())
        started = time.perf_counter()
        rows, manifest = rescore(previous, args.scratch, schema=not args.no_schema)
        for index, row in enumerate(rows, 1):
            state = row.get("error") or f"recall {row.get('recall', 0):.4f} f1 {row.get('hierarchyF1', 0):.3f}"
            note(f"{index:3d}/{len(rows)} {row['granuleId']}: {state}")
        measures = dict(previous)
        measures |= {
            "generatedAt": datetime.now(UTC).isoformat(),
            "revision": _revision(root),
            "profile": CFR_PROFILE.identity,
            "guideSha256": CFR_PROFILE.guide.sha256,
            "schemaSha256": CFR_PROFILE.schema_bundle[0].sha256,
            "gates": asdict(validate.DEFAULT_GATES),
            "documents": rows,
            "manifest": manifest,
            "wallSeconds": round(time.perf_counter() - started, 2),
            "scoredFrom": {
                "bodies": str(args.scratch),
                "fetchedAt": previous.get("generatedAt"),
                "fetchRevision": previous.get("revision"),
                "requests": previous.get("requests"),
            },
        }
        measures["summary"] = summarize(rows)
        if args.receipts:
            measures["receipts"] = str(args.receipts)
        args.output.write_text(json.dumps(measures, indent=2, sort_keys=True) + "\n")
        rewrite_report(args.report, render_block(measures))
        if args.receipts:
            write_receipts(args.receipts, measures, command=command, log=log)
        print(json.dumps({"output": str(args.output), "report": str(args.report), "rescored": len(rows)}))
        return 0

    api_key = read_api_key(args.env_file, args.env_var)
    scratch = args.scratch or Path(f"/tmp/reconstruction-benchmark-{datetime.now(UTC):%Y%m%dT%H%M%S}")
    scratch.mkdir(parents=True, exist_ok=True)
    per_edition = max(args.sections // len(EDITIONS), 1)
    budget = PagedJsonBudget(
        max_requests=3,
        max_page_bytes=16 * 1024 * 1024,
        timeout_seconds=args.timeout,
        min_request_interval_seconds=args.min_interval_seconds,
    )
    granules: list[Granule] = []
    listings: list[dict[str, Any]] = []
    listing_requests = 0
    try:
        with GovInfoDiscoveryReader(budget=budget, api_key=api_key) as reader:
            for edition in EDITIONS:
                listing = choose_granules(reader, edition, per_edition)
                granules.extend(listing.granules)
                listing_requests += 1
                listings.append(
                    {
                        "package": listing.granules[0].package,
                        "granulesListed": listing.listed,
                        "sectionGranules": listing.sections,
                        "declaredCount": listing.declared,
                        "listingComplete": listing.complete,
                        "stride": listing.stride,
                        "sampled": len(listing.granules),
                    }
                )
                note(f"listed {edition}: {len(granules)} granules so far")
    except CredentialRefusedError as error:
        print(f"credential refused; stopping: {scrub_credential(str(error), api_key)}", file=sys.stderr)
        return 1

    rows: list[dict[str, Any]] = []
    started = time.perf_counter()
    with KeylessBody(timeout_seconds=args.timeout, min_request_interval_seconds=args.min_interval_seconds) as bodies:
        for row in measure(
            granules,
            bodies,
            scratch,
            schema=not args.no_schema,
            max_requests=args.max_requests - listing_requests,
            api_key=api_key,
        ):
            rows.append(row)
            state = row.get("error") or f"recall {row.get('recall', 0):.4f} f1 {row.get('hierarchyF1', 0):.3f}"
            note(f"{len(rows):3d}/{len(granules)} {row['granuleId']}: {state}")
        body_requests = bodies.requests
        request_log = list(bodies.log)
    measures = {
        "generatedAt": datetime.now(UTC).isoformat(),
        "revision": _revision(root),
        "profile": CFR_PROFILE.identity,
        "guideSha256": CFR_PROFILE.guide.sha256,
        "schemaSha256": CFR_PROFILE.schema_bundle[0].sha256,
        "editions": [{"year": y, "title": t, "volume": v, "split": SPLITS.get(y, "blind")} for y, t, v in EDITIONS],
        "listings": listings,
        "targetSections": TARGET_SECTIONS,
        "requestedSections": args.sections,
        "gates": asdict(validate.DEFAULT_GATES),
        "requests": {
            "granuleListings": listing_requests,
            "bodies": body_requests,
            "total": listing_requests + body_requests,
        },
        "wallSeconds": round(time.perf_counter() - started, 2),
        "scratch": str(scratch),
        "documents": rows,
        "requestLog": request_log,
        "manifest": [
            {
                "granuleId": row["granuleId"],
                "split": row["split"],
                "pdfUrl": row["pdfUrl"],
                "pdfBytes": row.get("pdfBytes"),
                "pdfSha256": row.get("pdfSha256"),
                "xmlUrl": row["xmlUrl"],
                "xmlBytes": row.get("xmlBytes"),
                "xmlSha256": row.get("xmlSha256"),
            }
            for row in rows
            if "pdfSha256" in row
        ],
    }
    measures["summary"] = summarize(rows)
    if args.receipts:
        measures["receipts"] = str(args.receipts)
    args.output.write_text(json.dumps(measures, indent=2, sort_keys=True) + "\n")
    rewrite_report(args.report, render_block(measures))
    if args.receipts:
        write_receipts(args.receipts, measures, command=command, log=log)
    print(json.dumps({"output": str(args.output), "report": str(args.report), "requests": measures["requests"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
